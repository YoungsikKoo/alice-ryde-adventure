/* ===== SPRITE CACHE ===== */
_cache:{},
_inited:false,

/* ===== INIT: pre-render all sprites to canvases ===== */
init(){
  if(this._inited)return;
  this._inited=true;
  console.log("[CharacterSprites] init starting, defs:",Object.keys(this._defs).length);
  for(const[name,def]of Object.entries(this._defs)){
    if(!def||!def.pal)continue;
    const pal=def.pal;
    for(const[fkey,rows]of Object.entries(def)){
      if(fkey==="pal"||!rows||!Array.isArray(rows))continue;
      const h=rows.length;let w=0;for(let ri=0;ri<h;ri++){if(rows[ri]&&rows[ri].length>w)w=rows[ri].length;}
      const cv=document.createElement("canvas");
      cv.width=w*2;cv.height=h*2;
      const c=cv.getContext("2d");
      c.imageSmoothingEnabled=false;
      for(let py=0;py<h;py++){
        const row=rows[py];if(!row)continue;
        for(let px=0;px<row.length;px++){
          const ch=row[px];
          if(ch===".")continue;
          const ci=pal[ch];
          if(!ci)continue;
          const color=typeof ci==="number"?this.PAL[ci]:ci;
          if(!color)continue;
          c.fillStyle=color;
          c.fillRect(px*2,py*2,2,2);
        }
      }
      this._cache[name+"_"+fkey]=cv;
      /* auto-generate flipped version */
      const cvF=document.createElement("canvas");
      cvF.width=w*2;cvF.height=h*2;
      const cF=cvF.getContext("2d");
      cF.imageSmoothingEnabled=false;
      cF.translate(w*2,0);cF.scale(-1,1);
      cF.drawImage(cv,0,0);
      this._cache[name+"_"+fkey+"_flip"]=cvF;
    }
  }
  console.log("[CharacterSprites] init done, cached:",Object.keys(this._cache).length,"sprites");
},

/* ===== DRAW: render a character sprite ===== */
draw(ctx,type,x,y,w,h,dir,frame,sideView,isAttacking){
  if(!this._inited)this.init();
  if(!this._debugLogged){this._debugLogged={};};
  const f=frame%2;
  const ap=isAttacking?"atk":"";
  let key,flip=false;
  if(sideView){
    key=type+"_"+ap+"sr"+f;
    if(!this._cache[key]&&!this._cache[key+"_flip"])key=type+"_sr"+f;
    flip=(dir==="left");
  }else{
    if(dir==="left"){key=type+"_"+ap+"r"+f;if(!this._cache[key]&&!this._cache[key+"_flip"])key=type+"_r"+f;flip=true;}
    else if(dir==="right"){key=type+"_"+ap+"r"+f;if(!this._cache[key])key=type+"_r"+f;flip=false;}
    else{key=type+"_"+ap+dir[0]+f;if(!this._cache[key])key=type+"_"+dir[0]+f;}
  }
  const lookupKey=flip?key+"_flip":key;
  const cv=this._cache[lookupKey];
  if(!cv){
    if(!this._debugLogged[type]){this._debugLogged[type]=true;console.warn("[CharacterSprites] MISS type="+type+" key="+lookupKey+" dir="+dir+" sideView="+sideView+" cacheKeys="+Object.keys(this._cache).filter(k=>k.startsWith(type)).join(","));}
    /* fallback: try any available frame */
    const fb=this._cache[type+"_d0"];
    if(fb){ctx.drawImage(fb,Math.floor(x),Math.floor(y),w,h);return true;}
    return false;
  }
  ctx.drawImage(cv,Math.floor(x),Math.floor(y),w,h);
  return true;
},

